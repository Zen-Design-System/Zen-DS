/**
 * Assembles the public stylesheets of the library build (run after `vite build --config vite.lib.config.ts`).
 *
 *   dist/styles.css  Inter @font-face (url ./fonts/…) + tokens + text styles + effects + every component's CSS
 *   dist/reset.css   optional page reset (margins, box-sizing, Canvas background, Figma-matching text rendering)
 *   dist/fonts/      the Inter variable font files + licence
 *
 * Vite's lib mode inlines every asset as base64 (≈1.3 MB of font data inside the CSS), so the fonts are copied as
 * files instead. Platform-only styles (foundations.css, TASA Explorer, JetBrains Mono) never enter the package.
 *
 *   node scripts/build-lib-css.mjs [--out=dist]
 */
import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const outArg = process.argv.find((arg) => arg.startsWith("--out="));
const out = path.resolve(root, outArg ? outArg.slice(6) : process.env.ZEN_LIB_OUT ?? "dist");
const styles = path.join(root, "src/styles");
const read = (file) => fs.readFileSync(path.join(styles, file), "utf8").trim();

const componentsCss = path.join(out, "components.css");
if (!fs.existsSync(componentsCss)) {
  console.error(`✗ ${path.relative(root, componentsCss)} is missing — run the library build first (npm run build:lib).`);
  process.exit(1);
}

// Fonts: copy the files and point the @font-face urls at them.
const fontSource = path.join(root, "src/assets/fonts/Inter");
const fontOut = path.join(out, "fonts");
fs.mkdirSync(fontOut, { recursive: true });
for (const file of fs.readdirSync(fontSource)) fs.copyFileSync(path.join(fontSource, file), path.join(fontOut, file));
const fonts = read("fonts.css").replaceAll("../assets/fonts/Inter/", "./fonts/");

const banner = `/* @zen-ds/react — generated by scripts/build-lib-css.mjs. Import once: import "@zen-ds/react/styles.css"; */`;
const baseline = [
  "/* Zen components size with border-box even without reset.css. */",
  ':where([class*="zen-"]), :where([class*="zen-"])::before, :where([class*="zen-"])::after { box-sizing: border-box; }',
].join("\n");

const parts = [
  banner,
  fonts,
  "/* ── Tokens (Figma variables; modes via data-* attributes, see docs/getting-started.md) ── */",
  read("tokens.css"),
  "/* ── Text styles ── */",
  read("typography.css"),
  "/* ── Effect styles ── */",
  read("style-effects.css"),
  baseline,
  "/* ── Components ── */",
  fs.readFileSync(componentsCss, "utf8").trim(),
];
const css = `${parts.join("\n\n")}\n`;

const problems = [];
if (/data:font|data:application\/font|base64,d09G/i.test(css)) problems.push("inlined font data");
// The Dev font-family token may name JetBrains Mono (apps load it themselves); only the platform @font-face must stay out.
if (/@font-face\s*{[^}]*(TASA|JetBrains)/i.test(css)) problems.push("platform-only @font-face (TASA Explorer / JetBrains Mono)");
if (/\.foundation-|\.official-|\.pe-/.test(css)) problems.push("platform/docs class (.foundation-, .official-, .pe-)");
for (const match of css.matchAll(/url\(\s*["']?([^"')]+)["']?\s*\)/g)) {
  const target = match[1];
  if (target.startsWith("data:") || target.startsWith("#")) continue;
  if (!fs.existsSync(path.join(out, target))) problems.push(`broken url(${target})`);
}
if (problems.length) {
  console.error(`✗ styles.css: ${[...new Set(problems)].join("; ")}`);
  process.exit(1);
}

fs.writeFileSync(path.join(out, "styles.css"), css);
fs.writeFileSync(path.join(out, "reset.css"), `/* @zen-ds/react — optional page reset. Import after styles.css. */\n${read("reset.css")}\n`);
const entries = writeStyleEntries(fs.readFileSync(componentsCss, "utf8"));
fs.rmSync(componentsCss);

const kb = (bytes) => `${(bytes / 1024).toFixed(0)} KB`;
console.log(`✓ ${path.relative(root, path.join(out, "styles.css"))} ${kb(Buffer.byteLength(css))}, reset.css, fonts/ (${fs.readdirSync(fontOut).length} files)`);
console.log(`✓ ${path.relative(root, path.join(out, "css"))}/: base.css, ${entries.parts} parts, ${entries.names} style entries (import "@zen-ds/react/styles/<Component>")`);

/**
 * Per-component style entries (docs/research/per-component-css-spec-2026-10-24.md). An app that imports
 * "@zen-ds/react/styles/Dialog" loads the base (fonts, tokens, text styles, effects) and the CSS of Dialog and of every
 * component it renders, nothing else:
 *
 *   dist/css/base.css                styles.css without the components
 *   dist/css/parts/<src path>        each source CSS file, verbatim (components.css is exactly these, in order)
 *   dist/css/<Name>.js / .d.ts       side-effect imports of base.css and the parts the component's modules reach (and
 *                                    ZenProvider's, which every app renders), in the order of styles.css; bundlers load
 *                                    each CSS module once, at its first import
 *   dist/css/manifest.json           name → parts (zen-ds doctor checks an app's entries cover what it renders)
 *
 * A closure follows the built JS (static and dynamic imports between dist modules; types are gone) and the CSS each
 * module's source imports (the library JS has none).
 */
function writeStyleEntries(componentsText) {
  const stylesOut = path.join(out, "css");
  fs.rmSync(stylesOut, { recursive: true, force: true });
  const walk = (directory) => fs.readdirSync(directory, { withFileTypes: true }).flatMap((entry) => {
    const target = path.join(directory, entry.name);
    return entry.isDirectory() ? walk(target) : [target];
  });
  const src = path.join(root, "src");
  const modules = walk(out).filter((file) => file.endsWith(".js"));
  const sourceOf = (file) => {
    const base = path.join(src, path.relative(out, file).replace(/\.js$/, ""));
    return [".tsx", ".ts", ".jsx", ".mjs"].map((ext) => base + ext).find((candidate) => fs.existsSync(candidate));
  };
  const cssOf = new Map(modules.map((file) => {
    const source = sourceOf(file);
    const text = source ? fs.readFileSync(source, "utf8") : "";
    return [file, [...text.matchAll(/^\s*import\s+["']([^"']+\.css)["'];?/gm)].map((match) => path.resolve(path.dirname(source), match[1]))];
  }));
  const importsOf = new Map(modules.map((file) => {
    const text = fs.readFileSync(file, "utf8");
    const specifiers = [...text.matchAll(/(?:\bfrom\s*|\bimport\s*\(?\s*)["'](\.{1,2}\/[^"']+\.js)["']/g)].map((match) => path.resolve(path.dirname(file), match[1]));
    return [file, specifiers.filter((target) => cssOf.has(target))];
  }));

  // The parts: every CSS file a module imports, in the order Vite wrote them into components.css.
  const partFiles = [...new Set([...cssOf.values()].flat())];
  const position = new Map(partFiles.map((file) => [file, componentsText.indexOf(fs.readFileSync(file, "utf8").trim())]));
  const lost = partFiles.filter((file) => position.get(file) < 0);
  if (lost.length) fail(`css/parts: not in components.css as written: ${lost.map((file) => path.relative(root, file)).join(", ")}`);
  partFiles.sort((a, b) => position.get(a) - position.get(b));
  const normalise = (text) => text.replaceAll("/*$vite$:1*/", "").replace(/\s+/g, " ").trim();
  if (normalise(partFiles.map((file) => fs.readFileSync(file, "utf8")).join("\n")) !== normalise(componentsText)) {
    const rest = partFiles.reduce((text, file) => text.replace(fs.readFileSync(file, "utf8").trim(), ""), componentsText);
    fail(`css/parts: in order, the parts do not reproduce components.css; left over: ${normalise(rest).slice(0, 300)}`);
  }
  const partName = (file) => `parts/${path.relative(src, file).split(path.sep).join("/")}`;
  for (const file of partFiles) {
    const target = path.join(stylesOut, partName(file));
    fs.mkdirSync(path.dirname(target), { recursive: true });
    fs.writeFileSync(target, `${fs.readFileSync(file, "utf8").trim()}\n`);
  }

  // base.css: styles.css without the components; the fonts sit one folder up.
  const baseCss = `${[
    `/* @zen-ds/react — generated by scripts/build-lib-css.mjs. The shared base of the style entries (styles.css without the components). */`,
    fonts.replaceAll("./fonts/", "../fonts/"),
    read("tokens.css"), read("typography.css"), read("style-effects.css"), baseline,
  ].join("\n\n")}\n`;
  fs.writeFileSync(path.join(stylesOut, "base.css"), baseCss);

  // One entry per PascalCase export of the package entry, named after it.
  const index = path.join(out, "index.js");
  const indexText = fs.readFileSync(index, "utf8");
  const moduleOf = new Map();
  for (const match of indexText.matchAll(/^import\s*\{([^}]*)\}\s*from\s*["'](\.[^"']+)["']/gm)) {
    for (const name of match[1].split(",").map((part) => part.trim().split(/\s+as\s+/).pop()).filter(Boolean)) moduleOf.set(name, path.resolve(out, match[2]));
  }
  const exported = [...(indexText.match(/^export\s*\{([^}]*)\}/m)?.[1] ?? "").split(",")].map((part) => part.trim().split(/\s+as\s+/).pop()).filter(Boolean);
  const names = exported.filter((name) => /^[A-Z][a-z]/.test(name) && moduleOf.has(name));
  // Some modules write another component's classes without importing its module (AppShellHeader → app-shell.css,
  // Metric → chart.css): a `zen-<block>…` class the closure writes also brings the part named after its block, when that
  // part has the class in a selector.
  const selectorsOf = new Map(partFiles.map((file) => [file, new Set([...fs.readFileSync(file, "utf8").matchAll(/\.(zen-[\w-]+)/g)].map((match) => match[1]))]));
  const blocks = partFiles.map((file) => [path.basename(file, ".css"), file]).sort((a, b) => b[0].length - a[0].length);
  const ownerOf = (className) => {
    const name = className.slice(4);
    const owner = blocks.find(([block]) => name === block || name.startsWith(`${block}-`) || name.startsWith(`${block}_`))?.[1];
    return owner && [...selectorsOf.get(owner)].some((selector) => selector.startsWith(className)) ? owner : undefined;
  };
  const closure = (name) => {
    const seen = new Set();
    const stack = [moduleOf.get(name)];
    while (stack.length) {
      const file = stack.pop();
      if (seen.has(file)) continue;
      seen.add(file);
      stack.push(...(importsOf.get(file) ?? []));
    }
    const written = new Set([...seen].flatMap((module) => [...fs.readFileSync(module, "utf8").matchAll(/["'`\s](zen-[\w-]+)/g)].map((match) => match[1])));
    const owned = new Set([...written].map(ownerOf).filter(Boolean));
    return partFiles.filter((file) => owned.has(file) || [...seen].some((module) => cssOf.get(module)?.includes(file)));
  };
  // Every app renders ZenProvider (its toasts, its portal), so every entry brings its CSS too.
  const always = new Set(moduleOf.has("ZenProvider") ? closure("ZenProvider") : []);
  const manifest = {};
  for (const name of names) {
    const own = new Set(closure(name));
    const parts = partFiles.filter((file) => own.has(file) || always.has(file)).map(partName);
    manifest[name] = parts;
    const lines = ["base.css", ...parts].map((part) => `import "./${part}";`);
    fs.writeFileSync(path.join(stylesOut, `${name}.js`), `// @zen-ds/react — the CSS ${name} needs (scripts/build-lib-css.mjs).\n${lines.join("\n")}\n`);
    fs.writeFileSync(path.join(stylesOut, `${name}.d.ts`), "export {};\n");
  }
  fs.writeFileSync(path.join(stylesOut, "manifest.json"), `${JSON.stringify({ base: "base.css", components: manifest }, null, 2)}\n`);
  return { parts: partFiles.length, names: names.length };
}

function fail(message) {
  console.error(`✗ ${message}`);
  process.exit(1);
}
