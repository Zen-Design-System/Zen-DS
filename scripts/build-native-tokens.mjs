const aliasOf = (v) => (typeof v === "string" && v.startsWith("{") && v.endsWith("}") ? v.slice(1, -1) : null);
export const resolve = (name, ctx = {}) => {
  let cur = name;
  for (let i = 0; i < 32; i++) {
    const t = byName.get(cur);
    if (!t) return null;
    const modes = collections[t.collectionSlug].modes;
    const want = ctx[t.collectionSlug];
    const mode = want && want in t.valuesByMode ? want : modes[0];
    const v = t.valuesByMode[mode] ?? Object.values(t.valuesByMode)[0];
    const a = aliasOf(v);
    if (a) { cur = a; continue; }
    return { type: t.type, value: v };
  }
  return null;
};

export const resolveTextStyle = (name, ctx = {}) => {
  const d = textStyles[name];
  if (!d) return null;
  const get = (t) => resolve(t, ctx)?.value;
  return { family: get(d.family), size: get(d.size), weight: get(d.weight), lineHeight: get(d.lineHeight), letterSpacing: get(d.letterSpacing), uppercase: d.uppercase };
};

