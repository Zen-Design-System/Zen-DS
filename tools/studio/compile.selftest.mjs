#!/usr/bin/env node
// Builder page → React (compile.mjs, Studio builder GĐ5 M1): what each dialect feature compiles to, and that the output
// passes TypeScript (the repo's tsconfig: `@zen/design-system` is the library's source) and the usage harness as app
// code. Run: node tools/studio/compile.selftest.mjs   (--no-tsc skips the TypeScript pass, ~20 s)
import { spawnSync } from "node:child_process";
import fs from "node:fs";
import path from "node:path";
import { fileURLToPath, pathToFileURL } from "node:url";
import { compileReact, componentName } from "./compile.mjs";
import { newPageText, validateDialect } from "./dialect.mjs";

const here = path.dirname(fileURLToPath(import.meta.url));
const repo = path.resolve(here, "../..");
const failures = [];
let passed = 0;
function check(label, actual, expected) {
  const a = JSON.stringify(actual);
  const e = JSON.stringify(expected);
  if (a === e) passed += 1;
  else failures.push(`${label}\n    expected ${e}\n    actual   ${a}`);
}
const ok = (label, value) => check(label, Boolean(value), true);

const page = (title, imports, body, mock = "{}") => [
  `// @zen-page ${JSON.stringify({ format: 1, title })}`,
  `import { Board, Overlay, Screen, proto } from "@zen/design-system/builder";`,
  `import { ${imports} } from "@zen/design-system";`,
  "",
  `export const mock = ${mock};`,
  "",
  "export default function Page() {",
  "  return (",
  "    <Board>",
  ...body.map((line) => `      ${line}`),
  "    </Board>",
  "  );",
  "}",
  "",
].join("\n");

check("names: words, accents, digits", [componentName("Checkout · Pay"), componentName("Đặt hàng"), componentName("2024 plan"), componentName("")], ["CheckoutPay", "DatHang", "Studio2024Plan", "Studio"]);

// A blank page: one screen, no state, no props.
const blank = compileReact(newPageText({ title: "Checkout", device: "phone", chrome: false }), { file: "checkout.zen.tsx" });
check("blank: header, imports, no state", [blank.code.split("\n")[0], blank.code.includes('import { Stack, Text } from "@zen/design-system";'), blank.code.includes("useState")], ["// Generated by Zen Studio from checkout.zen.tsx. Edit the design, then export again.", true, false]);
ok("blank: the screen's content in place", blank.code.includes('      <Stack gap="md" padding="lg">\n        <Text textStyle="Heading/3">Checkout</Text>\n      </Stack>'));
check("blank: component and screens", [blank.component, blank.screens], ["CheckoutPage", [{ id: "screen-1", title: "Checkout", device: "phone", states: [] }]]);
// The app frame: an AppShell (Sidebar + Page Header) around the page on desktop, the bars above and below it on a phone.
const framedDesktop = compileReact(newPageText({ title: "Orders" }), { file: "orders.zen.tsx" }).code ?? "";
ok("frame (desktop): AppShell with the Sidebar, then the Page Header", /<AppShell sidebar=\{<Sidebar[\s\S]*\/>\}>\n\s*<PageHeader title="Orders" \/>\n\s*<Stack/.test(framedDesktop) && framedDesktop.includes('import { AppShell, PageHeader, Sidebar, Stack, Text } from "@zen/design-system";'));
const framedPhone = compileReact(newPageText({ title: "Orders", device: "phone" }), { file: "orders.zen.tsx" }).code ?? "";
ok("frame (phone): Top Navigation, the page, Bottom Navigation; no desktop parts", /<TopNavigation type="compact" title="Orders" \/>\n\s*<Stack[\s\S]*<\/Stack>\n\s*<BottomNavigation/.test(framedPhone) && !/Sidebar|PageHeader|AppShell/.test(framedPhone));

// Every feature: screens, a state variant, a list over the mock, navigate / back / open / toast / link, an overlay, a photo.
const full = page("Team", "Button, Dialog, EmptyState, Image, List, ListItem, Stack, Text", [
  '<Screen id="people" title="People" device="phone">',
  '  <Stack gap="md" padding="lg">',
  "    <Text textStyle=\"Heading/3\">{mock.team}</Text>",
  "    <List>",
  "      {mock.people.map((person) => <ListItem title={person.name} caption={person.role} onClick={proto.navigate(\"person\")} />)}",
  "    </List>",
  '    <Image src="zen-media:site-cafe" alt="Office" />',
  '    <Button level="primary" onClick={proto.open("invite")}>Invite</Button>',
  "  </Stack>",
  "</Screen>",
  '<Screen id="people" state="empty" title="People" device="phone">',
  '  <EmptyState title="No people yet" />',
  "</Screen>",
  '<Screen id="person" title="Person" device="phone">',
  '  <Stack gap="md" padding="lg">',
  '    <Button level="tertiary" onClick={proto.back()}>Back</Button>',
  '    <Button level="primary" onClick={proto.toast({ title: "Saved" })}>Save</Button>',
  '    <Button level="tertiary" onClick={proto.link("https://example.com/help")}>Help</Button>',
  "  </Stack>",
  "</Screen>",
  '<Overlay id="invite">',
  '  <Dialog title="Invite people" primaryAction={{ label: "Send", onClick: proto.close() }} secondaryAction={{ label: "Cancel", onClick: proto.close() }} />',
  "</Overlay>",
], '{ team: "Design", people: [{ name: "Ava Tran", role: "Designer" }, { name: "Bao Le", role: "Engineer", lead: true }] }');
check("full: the sample page is valid", validateDialect(full), []);
const team = compileReact(full, { file: "team.zen.tsx" });
check("full: compiles", team.error ?? null, null);
const code = team.code ?? "";
ok("full: mock type with an optional field", code.includes("export type TeamMock = {\n  team: string;\n  people: Array<{\n    name: string;\n    role: string;\n    lead?: boolean;\n  }>;\n};"));
ok("full: screen and overlay types", code.includes('export type TeamScreen = "people" | "person";') && code.includes('export type TeamOverlay = "invite";'));
ok("full: props for screen, state, navigation, back, data", ['screen?: TeamScreen;', 'state?: "empty";', "onNavigate?: (screen: TeamScreen) => void;", "onBack?: () => void;", "data?: TeamMock;"].every((line) => code.includes(line)));
ok("full: history, overlay, toast", ["const [history, setHistory] = useState<TeamScreen[]>([first]);", "const screen = history[history.length - 1];", "const [overlay, setOverlay] = useState<TeamOverlay | null>(null);", "const { toast } = useToast();"].every((line) => code.includes(line)));
ok("full: the state variant first", /\{screen === "people" && \(\n\s+state === "empty" \? \(\n\s+<EmptyState title="No people yet" \/>\n\s+\) : \(/.test(code));
ok("full: a list over the data, keyed", code.includes("{data.people.map((person, index) => (") && /<ListItem\s+key=\{index\}\s+title=\{person\.name\}\s+caption=\{person\.role\}\s+onClick=\{\(\) => navigate\("person"\)\}\s*\/>/.test(code));
ok("full: data reads the prop", code.includes("{data.team}"));
ok("full: the handlers", ['onClick={() => setOverlay("invite")}', "onClick={back}", 'onClick={() => toast({ title: "Saved" })}', 'onClick={() => window.open("https://example.com/help", "_blank", "noopener,noreferrer")}'].every((line) => code.includes(line)));
ok("full: the overlay is controlled", code.includes('open={overlay === "invite"}') && code.includes("onOpenChange={(open: boolean) => { if (!open) setOverlay(null); }}") && code.includes('primaryAction={{ label: "Send", onClick: () => setOverlay(null) }}'));
ok("full: the photo is an import", code.includes('import siteCafePhoto from "./assets/site-cafe.webp";') && code.includes("<Image src={siteCafePhoto} alt=\"Office\" />"));
check("full: media and handlers listed", [team.media, team.handlers.length], [[{ key: "site-cafe", kind: "media", file: "site-cafe.webp", name: "siteCafePhoto" }], 3]);
check("full: actions by frame", team.actions.map((entry) => `${entry.frame} ${entry.where} ${entry.action} ${typeof entry.target === "string" ? entry.target : ""}`.trim()), [
  "overlay:invite <Dialog> primaryAction.onClick close",
  "overlay:invite <Dialog> secondaryAction.onClick close",
  "screen:people <ListItem> onClick navigate person",
  "screen:people <Button> onClick open invite",
  "screen:person <Button> onClick back",
  "screen:person <Button> onClick toast",
  "screen:person <Button> onClick link https://example.com/help",
]);
ok("full: the data type", team.dataType?.startsWith("export type TeamMock = {"));
ok("full: the TODO block", code.includes(" * TODO(dev): the design's interactions, to wire to the app:"));

// What a component requires but a page cannot write (standins.mjs): a stand-in, and a Table column shows its row's field.
const required = compileReact(page("Orders", "AiChatField, Table, TopNavigation", [
  '<Screen id="orders" title="Orders" device="phone">',
  '  <TopNavigation title="Orders" searchAction={{ label: "Search orders" }} />',
  '  <Table aria-label="Orders" columns={[{ id: "name", header: "Name" }, { id: "total", header: "Total" }, { id: "note", header: "Note" }]} rows={mock.orders} />',
  '  <Table aria-label="Lines" columns={[{ id: "item", header: "Item" }]} rows={[{ id: "1", item: "Tea" }, { id: "2", item: "Cake" }]} />',
  '  <AiChatField placeholder="Ask" />',
  '  <SelectField label="Slot" options={[{ value: "a", label: "Thursday at 4 pm", at: "2026-10-01T16:00" }]} />',
  "</Screen>",
], '{ orders: [{ id: "o1", name: "Ava", total: 12, tags: ["new"] }] }').replace("AiChatField, Table", "AiChatField, SelectField, Table"), { file: "orders.zen.tsx" });
const requiredCode = required.code ?? "";
ok("stand-ins: an action object's onClick", requiredCode.includes('searchAction={{ label: "Search orders", onClick: () => {} }}'));
ok("stand-ins: a column shows its row's field (mock rows, rows in place)", ['{ id: "name", header: "Name", cell: (row) => row.name }', '{ id: "total", header: "Total", cell: (row) => row.total }', '{ id: "item", header: "Item", cell: (row) => row.item }'].every((line) => requiredCode.includes(line)));
ok("stand-ins: a column without such a field draws nothing", requiredCode.includes('{ id: "note", header: "Note", cell: () => null }'));
ok("known fields: an option's own data is left out", requiredCode.includes('options={[{ value: "a", label: "Thursday at 4 pm" }]}'));
ok("stand-ins: a required handler", requiredCode.includes('<AiChatField placeholder="Ask" onSubmit={() => {}} />'));
check("stand-ins: listed for the developer", required.handlers, ["<TopNavigation> searchAction.onClick: not in the design (a stand-in does nothing)", '<Table> column "note" draws nothing yet: write its cell', "<AiChatField> onSubmit: not in the design (a stand-in does nothing)"]);

// The outputs as app code: the usage harness (consumer mode) and TypeScript with the repo's settings.
const outputs = { "Checkout.tsx": blank.code, "Team.tsx": code, "Orders.tsx": requiredCode };
{
  const { rules } = await import(pathToFileURL(path.join(repo, "tools/usage-guard/check-usage.mjs")).href);
  const { createChecker } = await import(pathToFileURL(path.join(repo, "tools/usage-guard/engine.mjs")).href);
  const usage = createChecker(rules, { consumer: true, css: false });
  for (const [file, text] of Object.entries(outputs)) {
    const errors = usage.checkFile(text, `src/${file}`).filter((finding) => (finding.severity ?? finding.rule?.severity) === "error").map((finding) => `${finding.rule?.id ?? finding.rule}: ${finding.message ?? ""}`);
    check(`usage-guard: ${file} has no errors`, errors, []);
  }
}
if (!process.argv.includes("--no-tsc")) {
  const dir = path.join(repo, "node_modules/.cache/zen-studio/compile-check");
  fs.rmSync(dir, { recursive: true, force: true });
  fs.mkdirSync(dir, { recursive: true });
  for (const [file, text] of Object.entries(outputs)) fs.writeFileSync(path.join(dir, file), text);
  fs.writeFileSync(path.join(dir, "tsconfig.json"), JSON.stringify({ extends: path.relative(dir, path.join(repo, "tsconfig.json")), compilerOptions: { noUnusedLocals: true, noUnusedParameters: true }, include: [...Object.keys(outputs), path.relative(dir, path.join(repo, "src/vite-env.d.ts"))] }, null, 2));
  const tsc = spawnSync(process.execPath, [path.join(repo, "node_modules/typescript/bin/tsc"), "-p", path.join(dir, "tsconfig.json")], { encoding: "utf8" });
  const own = (tsc.stdout + tsc.stderr).split("\n").filter((line) => /compile-check\//.test(line));
  check("tsc: the outputs type-check (noUnusedLocals on)", own, []);
}

if (failures.length) {
  console.error(`✗ compile selftest: ${failures.length} failed, ${passed} passed\n  ${failures.join("\n  ")}`);
  process.exit(1);
}
console.log(`✓ compile selftest: ${passed} checks pass.`);
