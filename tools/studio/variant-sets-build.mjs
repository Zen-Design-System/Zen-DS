#!/usr/bin/env node
// Zen Studio Main component (spec docs/research/studio-main-component-spec-2026-10-09.md §3.2): the variant grid of
// every component, as its Figma component sets lay it out. Joins the Figma read (docs/figma-contracts/
// component-properties.json: each set's own VARIANT options, in Figma order), the map (tools/studio/figma-props.map.mjs:
// which sets a component covers and the code prop that picks one) and src/platform/studio/inspector/figmaProps.generated.ts
// (Figma option name → code value), then writes src/platform/studio/mainComponent/variantSets.generated.ts.
//
//   node tools/studio/variant-sets-build.mjs           write it
//   node tools/studio/variant-sets-build.mjs --check   exit 1 when it is stale
//
// A set's options are exactly the ones Figma has in that set (Button/Flat has 2 levels, Button/Main 9). Every Button set
// was read as a full grid (Size × Level × State = its variant count), so the grid draws every combination of them.
import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";
import { FIGMA_PROPS as MAP } from "./figma-props.map.mjs";
import { FIGMA_PROPS } from "../../src/platform/studio/inspector/figmaProps.generated.ts";

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "../..");
const OUT = "src/platform/studio/mainComponent/variantSets.generated.ts";
const check = process.argv.includes("--check");

const figma = JSON.parse(fs.readFileSync(path.join(root, "docs/figma-contracts/component-properties.json"), "utf8"));
const sets = new Map(figma.pages.flatMap((page) => page.sets.map((set) => [set.name, set])));

const out = {};
for (const [component, entry] of Object.entries(FIGMA_PROPS)) {
  const spec = MAP[component];
  if (!spec) continue;
  const result = [];
  for (const [setName, setValue] of Object.entries(spec.sets)) {
    const set = sets.get(setName);
    if (!set) continue;
    const axes = [];
    for (const prop of set.props) {
      if (prop.type !== "VARIANT") continue;
      const row = entry.own.find((own) => own.type === "VARIANT" && own.label === prop.name && own.options);
      if (!row) continue;
      const pairs = prop.options.map((name) => [name, row.options[name]]).filter(([, value]) => value !== undefined);
      // One value is no axis: the component shows it by itself.
      if (pairs.length < 2) continue;
      const fallback = row.options[prop.default] ?? pairs[0][1];
      axes.push({ prop: row.prop, label: prop.name, names: pairs.map(([name]) => name), values: pairs.map(([, value]) => value), default: fallback });
    }
    // Figma booleans that show a layer (Leading-Icon), off by Figma's default unless it says on; only plain values.
    const toggles = entry.toggles
      .filter((toggle) => typeof toggle.on === "string" && toggle.on !== "slot" && set.props.some((prop) => prop.name === toggle.label && prop.type === "BOOLEAN"))
      .map((toggle) => ({ prop: toggle.prop, label: toggle.label, on: toggle.on, default: Boolean(set.props.find((prop) => prop.name === toggle.label)?.default) }));
    result.push({ name: setName, figma: set.id, fixed: spec.setProp && setValue ? { [spec.setProp]: setValue } : {}, axes, toggles });
  }
  if (result.some((set) => set.axes.length)) out[component] = result;
}

const header = `// Generated by tools/studio/variant-sets-build.mjs from docs/figma-contracts/component-properties.json (Figma ${figma.file},\n// read ${figma.read}), tools/studio/figma-props.map.mjs and inspector/figmaProps.generated.ts. Do not edit: run the script.\n`;
const body = `${header}
/** One VARIANT property of a Figma set: the code prop, the Figma name, its options in Figma order (\`names\`) and their
 *  code values (\`values\`; "true" / "false" for a Yes / No variant held as a boolean), and Figma's default. */
export type VariantAxis = { prop: string; label: string; names: readonly string[]; values: readonly string[]; default: string };
/** A Figma boolean that shows a layer: on sets \`prop\` to \`on\` (an icon name), off leaves it out. */
export type VariantToggle = { prop: string; label: string; on: string; default: boolean };
/** A Figma component set as the Main component frame draws it: \`fixed\` are the code props that pick this set
 *  (Button/Flat: appearance "flat"), \`axes\` its variant properties. */
export type VariantSet = { name: string; figma: string; fixed: Readonly<Record<string, string>>; axes: readonly VariantAxis[]; toggles: readonly VariantToggle[] };

export const VARIANT_SETS: Readonly<Record<string, readonly VariantSet[]>> = ${JSON.stringify(out, null, 2)};
`;

const target = path.join(root, OUT);
const current = fs.existsSync(target) ? fs.readFileSync(target, "utf8") : null;
const counts = `${Object.keys(out).length} components, ${Object.values(out).reduce((n, list) => n + list.length, 0)} sets`;
if (check) {
  if (current !== body) { console.log(`✗ ${OUT} is stale: run node tools/studio/variant-sets-build.mjs`); process.exit(1); }
  console.log(`✓ Variant sets in sync (${counts})`);
} else {
  fs.mkdirSync(path.dirname(target), { recursive: true });
  if (current !== body) fs.writeFileSync(target, body);
  console.log(`✓ ${OUT}: ${counts}`);
}
