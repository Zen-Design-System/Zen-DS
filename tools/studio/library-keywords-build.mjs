#!/usr/bin/env node
// Keywords for the Studio library search (Studio builder GĐ3 M1, spec
// docs/research/studio-builder-library-spec-2026-10-06.md §3b), from docs/guidelines/index.json (227 KB, too big for
// the Studio bundle): per Zen component, the words of its guideline's `purpose` and `use` lines, and the intent words of
// other guidelines' `avoid` lines that point at it ("Choosing a filter, sort or scope → Chip": filter, sort, scope →
// Chip). Words are folded (lower case, Vietnamese marks dropped) like the search folds a query.
//   node tools/studio/library-keywords-build.mjs           write src/platform/studio/builder/library/keywords.generated.ts
//   node tools/studio/library-keywords-build.mjs --check   exit 1 when that file is out of date
import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "../..");
const SOURCE = path.join(root, "docs/guidelines/index.json");
const OUT = path.join(root, "src/platform/studio/builder/library/keywords.generated.ts");
/** At most this many words per component (the first ones: purpose, then use, then other guidelines' avoid lines). */
const MAX_WORDS = 30;
const STOP = new Set([
  "the", "and", "for", "with", "that", "this", "these", "those", "from", "into", "onto", "not", "are", "was", "were", "its", "their", "them",
  "they", "you", "your", "can", "may", "one", "two", "each", "any", "all", "only", "more", "most", "than", "then", "when", "where", "which",
  "while", "what", "who", "how", "use", "used", "uses", "using", "has", "have", "had", "but", "also", "own", "per", "via", "etc", "such", "other",
  "else", "out", "off", "too", "very", "just", "like", "over", "under", "about", "after", "before", "between", "without", "within", "both",
  "every", "some", "same", "there", "here", "does", "don", "doesn", "isn", "never", "always", "instead", "keep", "keeps", "let", "lets", "get",
  "gets", "put", "make", "makes", "show", "shows", "zen", "component", "components", "e.g", "i.e",
]);

const fold = (text) => String(text).toLowerCase().normalize("NFD").replace(/[̀-ͯ]/g, "").replace(/đ/g, "d").replace(/[^a-z0-9]+/g, " ").trim();
const wordsOf = (text) => fold(text).split(" ").filter((word) => word.length >= 3 && !STOP.has(word) && !/^\d+$/.test(word));

const guidelines = JSON.parse(fs.readFileSync(SOURCE, "utf8")).components;
const namesOf = (entry) => [...String(entry.import ?? "").matchAll(/import\s*\{([^}]*)\}/g)].flatMap((match) => match[1].split(",")).map((name) => name.trim().replace(/^type\s+/, "")).filter((name) => /^[A-Z]\w*$/.test(name));
const known = new Set(guidelines.flatMap(namesOf));

/** component name → ordered unique words */
const words = new Map();
const add = (name, list) => {
  if (!words.has(name)) words.set(name, []);
  const bucket = words.get(name);
  for (const word of list) if (!bucket.includes(word)) bucket.push(word);
};
for (const entry of guidelines) {
  const names = namesOf(entry);
  const own = [...wordsOf(entry.purpose ?? ""), ...(entry.use ?? []).flatMap(wordsOf)];
  for (const name of names) add(name, own);
}
// Intents that other guidelines send to a component: the words before "→", for every component named after it.
for (const entry of guidelines) {
  for (const line of entry.avoid ?? []) {
    const at = line.indexOf("→");
    if (at < 0) continue;
    const intent = wordsOf(line.slice(0, at));
    const targets = [...line.slice(at + 1).matchAll(/\b([A-Z][A-Za-z]+)\b/g)].map((match) => match[1]).filter((name) => known.has(name));
    for (const name of new Set(targets)) add(name, intent);
  }
}

const body = [...words.keys()].sort().map((name) => `  ${name}: ${JSON.stringify(words.get(name).slice(0, MAX_WORDS))},`).join("\n");
const text = `/* Generated by tools/studio/library-keywords-build.mjs from docs/guidelines/index.json. Do not edit directly. */

/** Per Zen component: folded words of its guideline (purpose, use) and of the avoid lines that point at it. */
export const GUIDELINE_KEYWORDS: Readonly<Record<string, readonly string[]>> = {
${body}
};
`;

if (process.argv.includes("--check")) {
  const current = fs.existsSync(OUT) ? fs.readFileSync(OUT, "utf8") : "";
  if (current !== text) {
    console.error("✗ library keywords out of date: run node tools/studio/library-keywords-build.mjs");
    process.exit(1);
  }
  console.log(`✓ library keywords in sync (${words.size} components)`);
} else {
  fs.mkdirSync(path.dirname(OUT), { recursive: true });
  fs.writeFileSync(OUT, text);
  console.log(`wrote ${path.relative(root, OUT)} (${words.size} components)`);
}
