#!/usr/bin/env node
// Zen Studio: the component each nested layer draws (Card › "Sub-Action" → IconButton), read from the nest() calls in
// src/components (tools/figma-contract/nested-paths.mjs nestedLayers). A page pushed to Figma (figma-push.mjs, core
// rebuild Q4) names the nested instance of each `overrides` entry with it, in the browser as in Node.
//
//   node tools/studio/nested-layers-build.mjs           write src/platform/studio/inspector/nestedLayers.generated.ts
//   node tools/studio/nested-layers-build.mjs --check   exit 1 when that file is out of date
import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";
import { nestedLayers } from "../figma-contract/nested-paths.mjs";

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "../..");
const target = path.join(root, "src/platform/studio/inspector/nestedLayers.generated.ts");
const output = `// Generated by tools/studio/nested-layers-build.mjs from src/components/**/*.tsx: do not edit by hand.
/** Owner component → its nested layers (nest() names) → the component each draws. */
export const NESTED_LAYERS: Readonly<Record<string, Readonly<Record<string, string>>>> = ${JSON.stringify(nestedLayers(), null, 2)};
`;

if (process.argv.includes("--check")) {
  const current = fs.existsSync(target) ? fs.readFileSync(target, "utf8") : "";
  if (current !== output) {
    console.error("✗ nestedLayers.generated.ts out of date: run node tools/studio/nested-layers-build.mjs");
    process.exit(1);
  }
  console.log(`✓ nested layers in sync (${Object.keys(nestedLayers()).length} components)`);
} else {
  fs.writeFileSync(target, output);
  console.log(`wrote ${path.relative(root, target)}`);
}
