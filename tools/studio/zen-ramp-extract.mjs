// Copies the Zen Figma plugin's colour ramp generator into the repo (Studio projects, 2026-10-17): Studio makes a
// project's Primary and Neutral ramps with the very function the plugin runs in Figma, so a colour picked in Studio
// gives the 12 solid + 12 alpha steps, Light and Dark, that the plugin would write to Global Colors.
//
//   node tools/studio/zen-ramp-extract.mjs [<plugin>/src/ui/main.js]     writes tools/studio/zen-ramp.generated.mjs
//   node tools/studio/zen-ramp-extract.mjs --check [<main.js>]            says when the plugin's algorithm moved on
//
// The plugin is a separate local git (default ~/Documents/zen-ds-figma-plugin-main). The script takes
// generateExpectedPalette and the On-Brand helpers with every top-level function and constant they reach (acorn), in
// source order, and replaces the plugin UI's `state` with the one value they read (darkBg).
//
// --check never fails a gate: the plugin is another repo, and its algorithm changing (2026-10-18, the Dark lift) made
// every session's studio:selftest fail on this Mac until the copy and Global Colors were regenerated together. It warns
// instead; what must hold is tools/studio/project-theme.selftest.mjs — the copy rebuilds the shipped Global Colors
// exactly — and the copy and global-colors.json move together (run this script, then regenerate the ramps).
import fs from "node:fs";
import os from "node:os";
import path from "node:path";
import { fileURLToPath } from "node:url";
import * as acorn from "acorn";

const here = path.dirname(fileURLToPath(import.meta.url));
const OUT = path.join(here, "zen-ramp.generated.mjs");
const ROOTS = ["generateExpectedPalette", "calculateOnBrandColor", "calculateOnBrandStateColor", "apcaContrast", "contrastRatio", "hexToOklch", "oklchToHex"];

const args = process.argv.slice(2);
const check = args.includes("--check");
const source = args.find((arg) => !arg.startsWith("--")) ?? path.join(os.homedir(), "Documents/zen-ds-figma-plugin-main/src/ui/main.js");

export function extract(text) {
  const ast = acorn.parse(text, { ecmaVersion: "latest", sourceType: "script" });
  const top = new Map();
  for (const node of ast.body) {
    if (node.type === "FunctionDeclaration") top.set(node.id.name, node);
    else if (node.type === "VariableDeclaration") for (const declaration of node.declarations) if (declaration.id.type === "Identifier") top.set(declaration.id.name, node);
  }
  const names = (node, out = new Set()) => {
    if (!node || typeof node !== "object") return out;
    if (Array.isArray(node)) { for (const item of node) names(item, out); return out; }
    if (node.type === "Identifier") out.add(node.name);
    for (const [key, value] of Object.entries(node)) {
      if (key === "start" || key === "end") continue;
      if (node.type === "MemberExpression" && key === "property" && !node.computed) continue;
      if (node.type === "Property" && key === "key" && !node.computed) continue;
      if (value && typeof value === "object") names(value, out);
    }
    return out;
  };
  const reached = new Set();
  const queue = [...ROOTS];
  while (queue.length) {
    const name = queue.shift();
    if (reached.has(name) || !top.has(name)) continue;
    reached.add(name);
    for (const id of names(top.get(name))) if (top.has(id) && !reached.has(id)) queue.push(id);
  }
  const missing = ROOTS.filter((name) => !reached.has(name));
  if (missing.length) throw new Error(`Not in the plugin: ${missing.join(", ")}`);
  const nodes = [...new Set([...reached].map((name) => top.get(name)))].sort((a, b) => a.start - b.start);
  const body = nodes.map((node) => {
    const code = text.slice(node.start, node.end);
    // The plugin UI's state object: only state.darkBg is read (the system dark background).
    if (node.type === "VariableDeclaration" && node.declarations.some((declaration) => declaration.id.name === "state")) return "var state = { darkBg: '#141414' };";
    return code;
  }).join("\n\n");
  return [
    "// GENERATED by tools/studio/zen-ramp-extract.mjs from the Zen Figma plugin (src/ui/main.js). Do not edit: rerun the",
    "// script after the plugin's ramp algorithm changes. Proven against the shipped Global Colors by",
    "// tools/studio/project-theme.selftest.mjs (every step of the 20 ramps, Light and Dark, solid and alpha).",
    "/* eslint-disable */",
    body,
    "",
    `export { ${ROOTS.join(", ")} };`,
    "",
  ].join("\n");
}

if (process.argv[1] && path.resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  if (!fs.existsSync(source)) {
    if (check) { console.log(`zen-ramp: the plugin is not at ${source}; the copy is checked by project-theme.selftest.mjs instead`); process.exit(0); }
    console.error(`zen-ramp: no plugin at ${source} (pass the path to its src/ui/main.js)`);
    process.exit(1);
  }
  const next = extract(fs.readFileSync(source, "utf8"));
  if (check) {
    const current = fs.existsSync(OUT) ? fs.readFileSync(OUT, "utf8") : "";
    if (current !== next) console.log("⚠ zen-ramp: the Zen plugin's ramp algorithm changed since tools/studio/zen-ramp.generated.mjs was copied. Run node tools/studio/zen-ramp-extract.mjs and regenerate tokens/source/figma/global-colors.json together (project-theme.selftest checks they agree).");
    else console.log("zen-ramp: the copy matches the plugin");
  } else {
    fs.writeFileSync(OUT, next);
    console.log(`zen-ramp: wrote ${path.relative(process.cwd(), OUT)} (${next.length} bytes)`);
  }
}
