// Zen AI kit for Figma: the skill, the Figma audit harness and the Markdown an AI agent (Claude, ChatGPT/Codex) needs
// to design screens in a Zen Figma file. One zip, built from the repo's own files so it never drifts:
//   - the docs platform builds it in the browser (Installation › AI kit for Figma, src/platform/aiKit.ts);
//   - `node tools/ai-kit/build.mjs` (npm run ai-kit:build) writes it to dist-pack/, `--check` (npm run ai-kit:check)
//     verifies it. files/README.md is the kit's own README.
// Isomorphic (browser and Node): the callers read the files, this module lays them out and writes the generated
// references (component properties, variables and styles).

export const KIT_NAME = "zen-figma-ai-kit";
export const SKILL = "zen-figma-design";
const SKILL_DIR = `skills/${SKILL}`;
const REFERENCES = `${SKILL_DIR}/references`;

/** The repo files the kit copies (paths from the repo root); the browser globs and build.mjs read exactly these. */
export const KIT_SOURCES = {
  /** Kit-level files: README.md and AGENTS.md (also written as CLAUDE.md). */
  root: "tools/ai-kit/files/",
  /** The skill folder, copied as it is. */
  skill: `${SKILL_DIR}/`,
  /** The Zen screen and component rules, copied into the skill's references. */
  rules: "docs/component-usage-rules.md",
  /** The principles the code skills keep (colour and composition, responsive and adaptive, UX states and flows, product
   *  patterns), copied into the skill's references. */
  principles: [
    "skills/zen-component-usage/references/design-principles.md",
    "skills/zen-responsive-screens/references/responsive-principles.md",
    "skills/zen-component-usage/references/ux-principles.md",
    "skills/zen-component-usage/references/product-patterns.md",
  ],
  guidelines: "docs/guidelines/",
  /** Data the generated references are written from. */
  contract: "docs/figma-contracts/component-properties.json",
  tokens: "tokens/source/figma/",
  tokenFiles: ["mode-colors-semantic", "spacing", "corner-radius", "breakpoint-grids", "emphasis-level", "typography-configuration"],
  styles: "styles/source/figma/styles.json",
  textStyles: "styles/source/figma/text-styles.json",
};

/** Where a copied repo file goes in the kit, or null when it is not part of it. */
export function kitPath(repoPath) {
  const path = repoPath.replace(/^\/+/, "");
  if (path.startsWith(KIT_SOURCES.root)) return path.slice(KIT_SOURCES.root.length);
  if (path.startsWith(KIT_SOURCES.skill)) return path;
  if (path === KIT_SOURCES.rules) return `${REFERENCES}/component-usage-rules.md`;
  if (KIT_SOURCES.principles.includes(path)) return `${REFERENCES}/${path.slice(path.lastIndexOf("/") + 1)}`;
  if (path.startsWith(KIT_SOURCES.guidelines) && path.endsWith(".md")) return `${REFERENCES}/guidelines/${path.slice(KIT_SOURCES.guidelines.length)}`;
  return null;
}

const GENERATED = "<!-- Generated by tools/ai-kit/kit.mjs from the Zen DS repo; edit the sources, not this file. -->";

/** Markdown table cell: no pipes or line breaks. */
const cell = (value) => String(value).replace(/\|/g, "\\|").replace(/\s*\n\s*/g, " ");

function propertyValues(prop) {
  if (prop.type === "VARIANT") return (prop.options ?? []).map((option) => (option === prop.default ? `**${option}**` : option)).join(" · ");
  if (prop.type === "BOOLEAN") return `${prop.default ? "**true**" : "**false**"} · ${prop.default ? "false" : "true"}`;
  if (prop.type === "TEXT") return `text, default “${prop.default ?? ""}”`;
  if (prop.type === "INSTANCE_SWAP") return `an icon or component; default ${prop.default ?? "—"}${prop.preferred ? ` (${prop.preferred.toLocaleString("en-US")} preferred values)` : ""}`;
  if (prop.type === "SLOT") return "slot: put your own layers in it";
  return "";
}

/** Every public Zen component set with its properties, from the Figma contract (docs/figma-contracts/component-properties.json). */
export function figmaComponentsMarkdown(contract) {
  const lines = [
    GENERATED,
    "# Zen Figma components and their properties",
    "",
    `Read from the live Zen Figma library (file \`${contract.file}\`, ${contract.read}) with the Plugin API's`,
    "`componentPropertyDefinitions`. Names are exact: pass them to `instance.setProperties()` with the `#id` suffix the",
    "file gives them (read `instance.componentProperties` first). Bold is the default value.",
    "",
    "- Change a component only through these properties. Never paint, resize or detach a layer inside an instance.",
    "- Do not set an INSTANCE_SWAP property to the value it already has: Figma re-creates the icon and it loses the",
    "  variant's colour (see figma-gotchas.md).",
    "- A SLOT holds your own layers (a page pattern's Content, a header's Sections). What you put there is yours and must",
    "  follow the same token rules as the rest of the screen.",
    "- Node ids are those of the Zen library file. In a file that uses the Zen library, import a set by name with",
    "  `search_design_system` (scoped to the Zen library key) or `figma.importComponentSetByKeyAsync`; in a copy of the",
    "  Zen file, find it by name on its ❖ page.",
    "",
  ];
  for (const page of contract.pages ?? []) {
    if (!page.sets?.length) continue;
    lines.push(`## ${page.page}`, "");
    for (const set of page.sets) {
      lines.push(`### ${set.name} · \`${set.id}\``, "");
      if (!set.props?.length) {
        lines.push("No properties.", "");
        continue;
      }
      lines.push("| Property | Type | Values |", "| --- | --- | --- |");
      for (const prop of set.props) lines.push(`| ${cell(prop.name)} | ${prop.type} | ${cell(propertyValues(prop))} |`);
      lines.push("");
    }
  }
  return `${lines.join("\n").trimEnd()}\n`;
}

/** `{dm-12}` → 12; `{Spacing/Padding/XLarge}` → "24 (Spacing/Padding/XLarge)"; a colour alias keeps its name. */
function resolveValue(value, dimensions, floats = {}) {
  if (typeof value !== "string") return value;
  const alias = value.match(/^\{(.+)\}$/);
  if (!alias) return value;
  if (alias[1] in dimensions) return dimensions[alias[1]];
  if (alias[1] in floats) return `${resolveValue(floats[alias[1]], dimensions, floats)} (${alias[1]})`;
  return alias[1];
}

// Modes the repo adds for Zen Studio's own chrome; they do not exist in Figma (docs/context/HANDOFF.md, Tokens).
const REPO_ONLY_MODES = new Set(["Studio"]);
const figmaModes = (collection) => collection.modes.filter((mode) => !REPO_ONLY_MODES.has(mode));

/** The variables and styles to bind, from tokens/source/figma and styles/source/figma. */
export function figmaTokensMarkdown({ collections, dimensions = {}, styles, textStyles }) {
  const lines = [
    GENERATED,
    "# Zen Figma variables and styles",
    "",
    "Bind every colour, gap, padding and radius you author to one of these variables, every text to a text style and",
    "every shadow to an effect style. Never bind the primitive collections (Global Colors, Base Colors (Project),",
    "Global Dimensions): they feed the variables below. Component Size and Component Theme belong to the components.",
    "",
  ];
  const byCollection = (name) => Object.entries(collections).find(([collection]) => collection === name)?.[1];
  // Single-mode number variables (Spacing) that other collections alias, such as Margin-Comfortable → Padding/XLarge.
  const floats = {};
  for (const collection of Object.values(collections)) {
    if (collection.modes.length !== 1) continue;
    for (const token of collection.tokens) if (token.type === "FLOAT") floats[token.name] = token.valuesByMode[collection.modes[0]];
  }

  const semantic = byCollection("Mode Colors (Semantic)");
  if (semantic) {
    lines.push("## Colour — Mode Colors (Semantic)", "", `Modes: ${semantic.modes.join(", ")}. Shown: the Light value's ramp step.`, "");
    const groups = new Map();
    for (const token of semantic.tokens) {
      const group = token.name.split("/").slice(0, 3).join("/");
      if (!groups.has(group)) groups.set(group, []);
      groups.get(group).push(token);
    }
    for (const [group, tokens] of groups) {
      lines.push(`### ${group}`, "");
      for (const token of tokens) lines.push(`- \`${token.name}\` — ${resolveValue(token.valuesByMode[semantic.modes[0]], dimensions)}`);
      lines.push("");
    }
  }

  const table = (title, collection, note) => {
    if (!collection) return;
    lines.push(`## ${title}`, "");
    if (note) lines.push(note, "");
    const modes = figmaModes(collection);
    lines.push(`| Variable | ${modes.join(" | ")} |`, `| --- | ${modes.map(() => "---").join(" | ")} |`);
    const first = (token) => Number(resolveValue(token.valuesByMode[collection.modes[0]], dimensions, floats)) || 0;
    const ordered = [...collection.tokens].sort((a, b) => a.name.split("/").slice(0, -1).join("/").localeCompare(b.name.split("/").slice(0, -1).join("/")) || first(a) - first(b));
    for (const token of ordered) {
      lines.push(`| \`${token.name}\` | ${modes.map((mode) => cell(resolveValue(token.valuesByMode[mode], dimensions, floats))).join(" | ")} |`);
    }
    lines.push("");
  };
  table("Spacing", byCollection("Spacing"), "Gap between siblings (`itemSpacing`) and padding inside a frame. The Zen ladder picks the step by relationship (screen-rules.md).");
  table("Corner radius", byCollection("Corner Radius"), "Modes are the file's corner styles; Rounded is the default.");
  table("Breakpoint & Grids", byCollection("Breakpoint & Grids"), "Screen margins, gutters and viewport sizes per device: set the screen frame's Breakpoint & Grids mode.");
  table("Emphasis Level", byCollection("Emphasis Level"));

  if (textStyles?.length) {
    const typography = byCollection("Typography Configuration");
    lines.push("## Text styles", "");
    if (typography) lines.push(`Sizes below are the ${typography.modes[0]} mode; the Typography Configuration modes (${figmaModes(typography).join(", ")}) change them. Set the mode on the screen frame, never resize text by hand.`, "");
    lines.push("| Style | Size | Weight |", "| --- | --- | --- |");
    for (const style of textStyles) lines.push(`| \`${style.name}\` | ${style.fontSize} | ${style.fontWeight} |`);
    lines.push("");
  }
  if (styles?.effectStyles?.length) {
    lines.push("## Effect styles", "");
    for (const style of styles.effectStyles) lines.push(`- \`${style.name}\`${style.value ? ` — ${cell(style.value)}` : ""}`);
    lines.push("");
  }
  if (styles?.colors?.length) {
    lines.push("## Colour styles (gradients, chart and avatar sets only)", "");
    lines.push(styles.colors.filter((style) => !style.name.startsWith(".")).map((style) => `\`${style.name}\``).join(" · "), "");
  }
  return `${lines.join("\n").trimEnd()}\n`;
}

/**
 * The kit's files, every path under `zen-figma-ai-kit/`.
 *   sources     { [repoPath]: text } — the files of KIT_SOURCES (root, skill, rules, guidelines)
 *   contract    the parsed component-properties.json
 *   tokenFiles  { [name]: parsed tokens/source/figma/<name>.json } plus "global-dimensions" for the dm-N values
 *   styles, textStyles  the parsed styles.json and text-styles.json
 */
export function buildKit({ sources, contract, tokenFiles, styles, textStyles, date = new Date() }) {
  const files = [];
  for (const [repoPath, text] of Object.entries(sources)) {
    const path = kitPath(repoPath);
    if (path) files.push({ path, data: text });
  }
  const agents = files.find((file) => file.path === "AGENTS.md");
  if (agents) files.push({ path: "CLAUDE.md", data: agents.data });

  const collections = {};
  const dimensions = {};
  for (const [name, json] of Object.entries(tokenFiles)) {
    for (const [collection, value] of Object.entries(json)) {
      if (name === "global-dimensions") for (const token of value.tokens) dimensions[token.name] = Object.values(token.valuesByMode)[0];
      else collections[collection] = value;
    }
  }
  files.push({ path: `${REFERENCES}/figma-components.md`, data: figmaComponentsMarkdown(contract) });
  files.push({ path: `${REFERENCES}/figma-tokens.md`, data: figmaTokensMarkdown({ collections, dimensions, styles: styles?.styles ?? styles, textStyles: textStyles?.textStyles ?? textStyles }) });

  const stamp = date.toISOString().slice(0, 10);
  files.push({ path: "VERSION.txt", data: `Zen AI kit for Figma, built ${stamp} from the Zen DS repo (Figma file 9nZv4uW2LT21yuHabMTCh1).\n` });
  return files
    .sort((a, b) => a.path.localeCompare(b.path))
    .map((file) => ({ path: `${KIT_NAME}/${file.path}`, data: file.data, date }));
}
