// The CSS contract: docs/css-contract.json, built with the guidelines (npm run guidelines:build; guidelines:check
// fails when it is stale). Plan docs/research/code-languages-plan-2026-10-03.md §3.B: once the docs show HTML snippets,
// the markup is public API, so for each component folder it lists what its stylesheets match and read:
//   classes     the .zen-* classes
//   attributes  the data-* attributes, with the values the CSS matches ([] when it matches the attribute alone)
//   properties  the --zen-* custom properties it declares or reads that are not design tokens (src/styles)
// A name that disappears is a breaking change for HTML users: the build refuses it unless CHANGELOG.md's Unreleased
// section has a "Breaking (markup)" line.
import fs from "node:fs";
import path from "node:path";

const stripComments = (css) => css.replace(/\/\*[\s\S]*?\*\//g, "");

/** Custom properties the design tokens define (src/styles/*.css): not part of any component's contract. */
function tokenNames(root) {
  const names = new Set();
  const dir = path.join(root, "src/styles");
  for (const file of fs.readdirSync(dir).filter((name) => name.endsWith(".css"))) {
    for (const match of stripComments(fs.readFileSync(path.join(dir, file), "utf8")).matchAll(/(--zen-[\w-]+)\s*:/g)) names.add(match[1]);
  }
  return names;
}

/** The selectors of a stylesheet (every prelude before a `{` that is not an at-rule). */
function selectorsOf(css) {
  const out = [];
  for (const match of stripComments(css).matchAll(/([^{};]+)\{/g)) {
    const prelude = match[1].trim();
    if (prelude && !prelude.startsWith("@")) out.push(prelude);
  }
  return out;
}

function contractOf(files, tokens) {
  const classes = new Set();
  const attributes = new Map();
  const properties = new Set();
  for (const file of files) {
    const css = fs.readFileSync(file, "utf8");
    for (const selector of selectorsOf(css)) {
      for (const match of selector.matchAll(/\.(zen-[\w-]+)/g)) classes.add(match[1]);
      for (const match of selector.matchAll(/\[\s*(data-[\w-]+)\s*(?:[~|^$*]?=\s*(?:"([^"]*)"|'([^']*)'|([\w-]+)))?\s*(?:i\s*)?\]/g)) {
        const values = attributes.get(match[1]) ?? new Set();
        const value = match[2] ?? match[3] ?? match[4];
        if (value !== undefined) values.add(value);
        attributes.set(match[1], values);
      }
    }
    for (const match of stripComments(css).matchAll(/(--zen-[\w-]+)/g)) if (!tokens.has(match[1])) properties.add(match[1]);
  }
  const sorted = (set) => [...set].sort();
  return {
    classes: sorted(classes),
    attributes: Object.fromEntries([...attributes].sort(([a], [b]) => a.localeCompare(b)).map(([name, values]) => [name, sorted(values)])),
    properties: sorted(properties),
  };
}

/** Every entry of `previous` that `next` no longer has: "Button: .zen-button__icon", "Card: [data-size=\"xl\"]". */
export function removedEntries(previous, next) {
  const removed = [];
  for (const [component, before] of Object.entries(previous?.components ?? {})) {
    const after = next.components[component] ?? { classes: [], attributes: {}, properties: [] };
    for (const name of before.classes) if (!after.classes.includes(name)) removed.push(`${component}: .${name}`);
    for (const [name, values] of Object.entries(before.attributes)) {
      if (!(name in after.attributes)) { removed.push(`${component}: [${name}]`); continue; }
      for (const value of values) if (!after.attributes[name].includes(value)) removed.push(`${component}: [${name}="${value}"]`);
    }
    for (const name of before.properties) if (!after.properties.includes(name)) removed.push(`${component}: ${name}`);
  }
  return removed;
}

/** Whether CHANGELOG.md's Unreleased section owns up to a markup break. */
export function changelogAllowsMarkupBreak(root) {
  const text = fs.readFileSync(path.join(root, "CHANGELOG.md"), "utf8");
  const start = text.search(/^## \[[^\]]+\] — Unreleased/m);
  if (start < 0) return false;
  const rest = text.slice(start + 1);
  const end = rest.search(/^## \[/m);
  return /Breaking \(markup\)/.test(end < 0 ? rest : rest.slice(0, end));
}

/** The contract of every component folder with a stylesheet, as the file's text and as data. */
export function cssContract(root) {
  const tokens = tokenNames(root);
  const dir = path.join(root, "src/components");
  const components = {};
  for (const folder of fs.readdirSync(dir).sort()) {
    if (folder.startsWith("_")) continue;
    const folderPath = path.join(dir, folder);
    if (!fs.statSync(folderPath).isDirectory()) continue;
    const files = fs.readdirSync(folderPath).filter((name) => name.endsWith(".css") && !name.endsWith(".stories.css")).map((name) => path.join(folderPath, name));
    if (files.length) components[folder] = contractOf(files, tokens);
  }
  const data = {
    $comment: "Generated by tools/code-languages/css-contract.mjs (npm run guidelines:build). The markup API of each component for HTML users: the .zen-* classes, data-* attributes (with the values the CSS matches) and non-token --zen-* custom properties its stylesheets use. Removing one is a CHANGELOG \"Breaking (markup)\" change.",
    components,
  };
  return { data, text: `${JSON.stringify(data, null, 2)}\n` };
}
