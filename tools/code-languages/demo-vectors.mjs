// The demo formatters' test vectors: platforms/tests/demo-vectors.json, built with the guidelines (npm run
// guidelines:build; guidelines:check fails when it is stale). Plan docs/research/code-languages-plan-2026-10-03.md §4.3
// and §11: every example imports the same demo world (src/platform/examples/data.ts, shown as ./demo), and each language
// port writes its own demo module whose formatters must print the same dates, money and sizes. The ports' tests assert
// these vectors, the way the token vectors (platforms/tests/vectors.json) work.
//
// A date is { "date": [year, month (1–12), day, hour, minute] } in local time: the formatters read local fields only.
import path from "node:path";
import { createRequire } from "node:module";

/** examples/data.ts as a module Node can run: types stripped and its photos left out (esbuild, in memory). */
async function loadDemo(root) {
  const require = createRequire(path.join(root, "package.json"));
  const esbuild = require("esbuild");
  const out = await esbuild.build({
    entryPoints: [path.join(root, "src/platform/examples/data.ts")],
    bundle: true, write: false, format: "esm", platform: "neutral", logLevel: "silent",
    loader: { ".webp": "empty", ".jpg": "empty", ".png": "empty" },
  });
  return import(`data:text/javascript;base64,${Buffer.from(out.outputFiles[0].text).toString("base64")}`);
}

const date = (y, m, d, h = 0, min = 0) => ({ date: [y, m, d, h, min] });
const toDate = (value) => (value && typeof value === "object" && Array.isArray(value.date) ? new Date(value.date[0], value.date[1] - 1, value.date[2], value.date[3], value.date[4]) : value);
const fromDate = (value) => (value instanceof Date ? date(value.getFullYear(), value.getMonth() + 1, value.getDate(), value.getHours(), value.getMinutes()) : value);

/** The inputs: each formatter's branches, around Today (Wednesday, Sep 30, 2026, 10:30 am). */
const CASES = {
  initials: [["Bao Nguyen"], ["Minh Anh Vo"], ["Alex"], ["  Gia   Pham "], [""]],
  daysFromToday: [[0], [2], [-1, 16, 5], [33]],
  formatDate: [[date(2026, 10, 12)], [date(2027, 1, 2)]],
  formatDay: [[date(2026, 10, 12)], [date(2026, 9, 1)]],
  formatRange: [[date(2026, 10, 12), date(2026, 10, 14)], [date(2026, 12, 30), date(2027, 1, 2)]],
  formatTime: [[date(2026, 9, 30, 10, 30)], [date(2026, 9, 30, 0, 5)], [date(2026, 9, 30, 12, 0)], [date(2026, 9, 30, 23, 59)]],
  formatRelative: [
    [date(2026, 9, 30, 10, 30)], [date(2026, 9, 30, 10, 29)], [date(2026, 9, 30, 10, 17)], [date(2026, 9, 30, 9, 12)],
    [date(2026, 9, 29, 16, 40)], [date(2026, 9, 27, 11, 0)], [date(2026, 9, 14, 10, 30)], [date(2025, 9, 14, 10, 30)],
  ],
  formatDue: [[date(2026, 9, 30, 18, 0)], [date(2026, 10, 1)], [date(2026, 10, 5)], [date(2026, 9, 29)], [date(2026, 9, 28)]],
  formatMoney: [[1280.4], [12000], [12000, true], [9140.5], [0]],
  formatCompactMoney: [[20500], [1152], [262500], [1250000]],
  formatBytes: [[999], [86000], [1240000], [18400000], [214000000], [4200000000]],
};

/** The vectors file's text: what the demo module answers today. */
export async function demoVectors(root) {
  const demo = await loadDemo(root);
  const vectors = [];
  for (const [fn, list] of Object.entries(CASES)) {
    if (typeof demo[fn] !== "function") throw new Error(`examples/data.ts has no function ${fn} (tools/code-languages/demo-vectors.mjs)`);
    for (const args of list) vectors.push({ fn, args, expected: fromDate(demo[fn](...args.map(toDate))) });
  }
  // One vector per line.
  const comment = "Generated by tools/code-languages/demo-vectors.mjs from src/platform/examples/data.ts (the examples' ./demo). Every language's demo module must give these answers. A date is { date: [year, month 1–12, day, hour, minute] } in local time; Today is Sep 30, 2026, 10:30 am.";
  const lines = vectors.map((vector) => `    ${JSON.stringify(vector)}`).join(",\n");
  return `{\n  "$comment": ${JSON.stringify(comment)},\n  "today": ${JSON.stringify(date(2026, 9, 30, 10, 30))},\n  "vectors": [\n${lines}\n  ]\n}\n`;
}
