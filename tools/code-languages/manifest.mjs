// The Code view's status per component and language: src/platform/code-languages.generated.json. Built with the
// guidelines (npm run guidelines:build); npm run guidelines:check fails when it is stale.
// Plan: docs/research/code-languages-plan-2026-10-03.md §3.E.
//
// React is the reference: every public component is "ready" in it. Another language is "ready" for a component only
// when its port lists the component, "markup" when only its static markup works without JavaScript, else "not-yet".
// A language lists its components in platforms/<language>/code-language.json, written by its parity gate:
//   { "ready": ["Badge", …], "markup": ["Dialog", …] }
// No file: nothing is available in that language yet, and the Code view says so.
import fs from "node:fs";
import path from "node:path";

/** The Code view's languages, in the order the picker lists them (the user's order, 2026-10-08). */
export const CODE_LANGUAGES = ["react", "html", "vue", "swift", "flutter", "svelte"];

function readLanguage(root, language, known) {
  const file = path.join(root, "platforms", language, "code-language.json");
  if (!fs.existsSync(file)) return { ready: new Set(), markup: new Set() };
  const data = JSON.parse(fs.readFileSync(file, "utf8"));
  const ready = new Set(data.ready ?? []);
  const markup = new Set(data.markup ?? []);
  const unknown = [...ready, ...markup].filter((name) => !known.has(name));
  if (unknown.length) throw new Error(`${path.relative(root, file)} lists components the library does not export: ${unknown.join(", ")}`);
  return { ready, markup };
}

/**
 * The manifest's text: one line per public component (export name → its guideline slug and a status per language),
 * so a port that adds a component changes one line.
 * @param {Map<string, { components: Array<{ name: string }> }>} bySlug buildApi(…).bySlug
 */
export function codeLanguagesManifest(bySlug, root) {
  const slugOf = new Map();
  for (const [slug, entry] of bySlug) for (const component of entry.components) if (!slugOf.has(component.name)) slugOf.set(component.name, slug);
  const known = new Set(slugOf.keys());
  const languages = Object.fromEntries(CODE_LANGUAGES.slice(1).map((language) => [language, readLanguage(root, language, known)]));
  const rows = [...slugOf].sort(([a], [b]) => a.localeCompare(b)).map(([name, slug]) => {
    const status = { slug, react: "ready" };
    for (const [language, { ready, markup }] of Object.entries(languages)) status[language] = ready.has(name) ? "ready" : markup.has(name) ? "markup" : "not-yet";
    return `    ${JSON.stringify(name)}: ${JSON.stringify(status)}`;
  });
  return [
    "{",
    `  "$comment": "Generated by tools/code-languages/manifest.mjs (npm run guidelines:build). The Code view's status per component: ready · markup (static markup only, behaviour needs JavaScript) · not-yet. A language lists its components in platforms/<language>/code-language.json.",`,
    `  "languages": ${JSON.stringify(CODE_LANGUAGES)},`,
    '  "components": {',
    rows.join(",\n"),
    "  }",
    "}",
    "",
  ].join("\n");
}
