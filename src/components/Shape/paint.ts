/** A variable's custom property, as scripts/build-tokens.mjs names it ("Color/Background/Black-Solid/Default" →
 *  "--zen-color-background-black-solid-default"). */
export const cssVarOf = (variable: string) => `--zen-${variable.toLowerCase().replace(/[^a-z0-9]+/g, "-").replace(/^-|-$/g, "")}`;

/** `var(--token)` for a fill, or undefined for "none" / an unknown value. */
export function fillPaint(fill: string | undefined): string | undefined {
  const token = fill && fill !== "none" ? (shapeFillTokens as Record<string, string>)[fill] : undefined;
  return token ? `var(${cssVarOf(token)})` : undefined;
}
/** `var(--token)` for a stroke, or undefined for "none" / an unknown value. */
export function strokePaint(stroke: string | undefined): string | undefined {
  const token = stroke && stroke !== "none" ? (shapeStrokeTokens as Record<string, string>)[stroke] : undefined;
  return token ? `var(${cssVarOf(token)})` : undefined;
}
